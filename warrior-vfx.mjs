export function vfxDefinition(id) {
  const fx = WARRIOR_VFX[id];
  if (!fx) return null;
  return {
    folha: `/assets/fx/royal-warrior/${id}.png`,
    quadro: [128, 128],
    frames: fx.frames,
    fps: fx.fps,
    pivo: fx.pivot,
    camada: fx.layer,
    alturaTela: fx.height,
    ...(fx.direction ? { orientacao: "direita", espelharAoVirar: true } : {}),
    ...(fx.complete ? { inteiro: true } : {}),
    ...(fx.area ? { larguraArea: fx.area } : {}),
    ...(fx.feet ? { ancora: "pes" } : {}),
    ...(fx.loop ? { loop: true } : {}),
  };
}
